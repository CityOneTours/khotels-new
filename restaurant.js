let currentCategory = 'all';

function renderMenu(category) {
    const menuGrid = document.getElementById('menuGrid');
    menuGrid.innerHTML = '';

    const filteredItems = category === 'all'
        ? menuItems
        : menuItems.filter(item => item.category === category);

    filteredItems.forEach(item => {
        const menuCard = `
                    <div class="menu-item">
                        <img src="${item.image}" alt="${item.name}">
                        <div class="item-details">
                            <div class="item-name">${item.name}</div>
                            <div class="item-description">${item.description}</div>
                            <div class="item-footer">
                                
                            </div>
                        </div>
                    </div>
                `;
        menuGrid.innerHTML += menuCard;
    });
}

function filterMenu(category) {
    currentCategory = category;
    renderMenu(category);

    document.querySelectorAll('.category-btn').forEach(btn => {
        btn.classList.remove('active');
    });
    event.target.classList.add('active');
}

function openModal() {
    document.getElementById('enquiryModal').classList.add('active');
    document.getElementById('successMessage').classList.add('hidden');
    document.getElementById('enquiryForm').classList.remove('hidden');
}

function closeModal() {
    document.getElementById('enquiryModal').classList.remove('active');
    document.getElementById('enquiryForm').reset();
}

document.getElementById('enquiryForm').addEventListener('submit', function (e) {
    e.preventDefault();

    document.getElementById('enquiryForm').classList.add('hidden');
    document.getElementById('successMessage').classList.remove('hidden');

    setTimeout(() => {
        closeModal();
    }, 3000);
});

window.onclick = function (event) {
    const modal = document.getElementById('enquiryModal');
    if (event.target === modal) {
        closeModal();
    }
}

renderMenu('all');